# --------------------------------------------------------------------------
# THE SCENE - a flat, drawn back to front
# --------------------------------------------------------------------------
W, H = 9, 7
PEOPLE = [
    (2.7, 1.1, "skin_a", 0),     # kitchen, at the hob
    (6.6, 2.5, "skin_b", 1),     # bedroom
    (2.6, 4.6, "skin_c", 2),     # living, on the rug
]
SKINS = [(232, 190, 156), (156, 112, 84), (198, 152, 118)]
HAIRS = [(58, 44, 38), (28, 26, 30), (128, 92, 54)]

def scene(st):
    pad_x, pad_y = 40, 150
    ow = (W + H) * HW + pad_x * 2
    oh = (W + H) * HH + pad_y + 120
    img = Image.new("RGB", (ow, oh), st.bg)
    d = ImageDraw.Draw(img, "RGBA")
    ox, oy = pad_x + H * HW, pad_y

    for y in range(H):
        for x in range(W):
            o_floor(d, st, ox, oy, x, y)
    o_rug(d, st, ox, oy, 0.7, 4.5, 2.6, 2.1)

    # Depth order: everything keyed on the far corner of its footprint.
    items = []
    def add(x, y, fn, *a): items.append((x + y, len(items), x, y, fn, a))

    # Boundary, as two runs rather than 16 panels.
    add(0, -0.14, o_wall, "ew", W)
    add(-0.14, 0, o_wall, "ns", H)
    # Interior walls. Each run stops short of the next: the gap IS the door.
    add(4.5, -0.14, o_wall, "ns", 2.5)          # kitchen | bedroom
    add(4.5, 3.4, o_wall, "ns", 3.7)            # living  | bathroom
    add(4.5, 3.5, o_wall, "ew", 2.6)            # bedroom | bathroom
    add(8.2, 3.5, o_wall, "ew", 0.9)

    # Kitchen, north-west
    add(0, 0, o_counter, "plain"); add(1, 0, o_counter, "sink"); add(2, 0, o_counter, "hob")
    add(3, 0, o_fridge)
    add(1.1, 2.0, o_table); add(1.1, 3.1, o_chair); add(0.1, 2.0, o_chair)
    # Living, south-west
    add(1.0, 5.0, o_sofa); add(3.3, 5.6, o_tv); add(0.1, 4.2, o_lamp)
    # Bedroom, north-east
    add(6.0, 0.1, o_bed); add(8.0, 0.2, o_bookcase); add(8.1, 2.4, o_plant)
    # Bathroom, south-east
    add(5.2, 5.6, o_bath); add(7.7, 4.4, o_toilet); add(8.0, 5.8, o_shower)
    add(3.6, 4.2, o_plant)

    for i, (x, y, _, _) in enumerate(PEOPLE):
        items.append((x + y + .4, 900 + i, x, y, "sim", (i,)))

    glows = []
    for _, _, x, y, fn, a in sorted(items, key=lambda t: (t[0], t[1])):
        if fn == "sim":
            i = a[0]
            sim(d, st, ox, oy, x, y, SKINS[i], HAIRS[i],
                st.pal["accents"][i % len(st.pal["accents"])],
                mul(st.c("dark"), 1.9 if st.key != "bold" else 2.4))
        else:
            r = fn(d, st, ox, oy, x, y, *a)
            if isinstance(r, tuple) and r[0] == "glow":
                glows.append(r[1:])
    for g, pos in glows:
        img.paste(Image.alpha_composite(
            img.crop((pos[0], pos[1], pos[0] + g.width, pos[1] + g.height)).convert("RGBA"), g
        ).convert("RGB"), pos)

    if st.grain:
        import random
        random.seed(3)
        g = Image.new("L", img.size)
        gp = g.load()
        for yy in range(img.height):
            for xx in range(img.width):
                gp[xx, yy] = 236 + random.randint(0, 19)
        img = Image.composite(img, Image.new("RGB", img.size, (0, 0, 0)), g.point(lambda v: v))
        img = Image.blend(img, Image.new("RGB", img.size, st.bg), 0.0)
        from PIL import ImageChops
        img = ImageChops.multiply(img, Image.merge("RGB", (g, g, g)))
    return img


for st in STYLES:
    im = scene(st)
    p = f"{OUT}/{st.key}.png"
    im.save(p, optimize=True)
    print(f"{st.key:12s} {st.name:18s} {im.size}  {os.path.getsize(p)//1024} KB")
