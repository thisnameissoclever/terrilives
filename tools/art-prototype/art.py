def o_floor(d, st, ox, oy, x, y):
    a, b = st.c("floor"), st.c("floor2")
    col = a if (x + y) % 2 == 0 else b
    pts = [(ox + sx(x, y), oy + sy(x, y)),
           (ox + sx(x + 1, y), oy + sy(x + 1, y)),
           (ox + sx(x + 1, y + 1), oy + sy(x + 1, y + 1)),
           (ox + sx(x, y + 1), oy + sy(x, y + 1))]
    d.polygon(pts, fill=col, outline=st.c("grout"), width=1)


def o_wall(d, st, ox, oy, x, y, axis, length=1, height=1.75):
    """A wall on a tile EDGE, drawn as ONE box for the whole RUN.

    Two things the shipped renderer does not do, and both are why its
    walls read as a picket fence. It puts a half-tile-wide panel at the
    tile CENTRE (tiles.ts says so: "a 32 px panel on a 64 px tile already
    leaves floor showing beside every wall"), and it emits one instance
    per tile, so any per-panel edge repeats every 32 px and the run
    stripes. On the edge and in one piece, a run is a surface. This is
    [B7].
    """
    t = 0.14
    c = st.c("wall")
    if axis == "ew":
        box(d, st, ox, oy, x, y, x + length, y + t, 0, height, c, top_c=st.c("wall_top"))
        if st.c("skirt"):
            box(d, st, ox, oy, x, y, x + length, y + t + .02, 0, .14, st.c("skirt"))
    else:
        box(d, st, ox, oy, x, y, x + t, y + length, 0, height, c, top_c=st.c("wall_top"))
        if st.c("skirt"):
            box(d, st, ox, oy, x, y, x + t + .02, y + length, 0, .14, st.c("skirt"))


def o_rug(d, st, ox, oy, x, y, w=2, h=2):
    col = st.pal["accents"][1]
    pts = [(ox + sx(x, y), oy + sy(x, y)),
           (ox + sx(x + w, y), oy + sy(x + w, y)),
           (ox + sx(x + w, y + h), oy + sy(x + w, y + h)),
           (ox + sx(x, y + h), oy + sy(x, y + h))]
    d.polygon(pts, fill=col, outline=st.outline, width=st.outline_w)
    inner = [(ox + sx(x + .22, y + .22), oy + sy(x + .22, y + .22)),
             (ox + sx(x + w - .22, y + .22), oy + sy(x + w - .22, y + .22)),
             (ox + sx(x + w - .22, y + h - .22), oy + sy(x + w - .22, y + h - .22)),
             (ox + sx(x + .22, y + h - .22), oy + sy(x + .22, y + h - .22))]
    d.polygon(inner, fill=mul(col, 1.14), outline=st.outline, width=st.outline_w)


