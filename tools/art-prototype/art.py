def box(d, st, ox, oy, x0, y0, x1, y1, z0, z1, colour, *, top_c=None, flat=False):
    """An axis-aligned box in tile space, drawn as its three visible faces."""
    zt, zb = z1 * PX_PER_TILE_Z, z0 * PX_PER_TILE_Z
    def P(x, y, z): return (ox + sx(x, y), oy + sy(x, y) - z)

    N, E, S, W = (x0, y0), (x1, y0), (x1, y1), (x0, y1)
    top = [P(*N, zt), P(*E, zt), P(*S, zt), P(*W, zt)]
    right = [P(*E, zt), P(*S, zt), P(*S, zb), P(*E, zb)]
    left = [P(*W, zt), P(*S, zt), P(*S, zb), P(*W, zb)]

    ol = st.outline
    w = st.outline_w
    tc = top_c or colour
    if flat:
        cl = cr = ct = colour
    else:
        ct = mul(tc, st.top)
        cr = mul(colour, st.right)
        cl = mul(colour, st.left)
    d.polygon(left, fill=cl, outline=ol, width=w)
    d.polygon(right, fill=cr, outline=ol, width=w)
    d.polygon(top, fill=ct, outline=ol, width=w)
    if st.edge_light:                      # a lit lip along the top edges
        d.line([top[3], top[0], top[1]], fill=st.edge_light, width=1)


def slab(d, st, ox, oy, x0, y0, x1, y1, z, colour, thick=0.06):
    box(d, st, ox, oy, x0, y0, x1, y1, z - thick, z, colour)


def cyl(d, st, ox, oy, cx, cy, r, z0, z1, colour):
    """Good enough for lamps, plants, mugs: an ellipse-topped column."""
    zt, zb = z1 * PX_PER_TILE_Z, z0 * PX_PER_TILE_Z
    px, py = ox + sx(cx, cy), oy + sy(cx, cy)
    rx, ry = r * HW * 1.3, r * HH * 1.3
    body = [(px - rx, py - zt), (px + rx, py - zt), (px + rx, py - zb), (px - rx, py - zb)]
    d.polygon(body, fill=mul(colour, st.right), outline=st.outline, width=st.outline_w)
    d.ellipse([px - rx, py - zb - ry, px + rx, py - zb + ry], fill=mul(colour, st.right),
              outline=st.outline, width=st.outline_w)
    d.ellipse([px - rx, py - zt - ry, px + rx, py - zt + ry], fill=mul(colour, st.top),
              outline=st.outline, width=st.outline_w)


