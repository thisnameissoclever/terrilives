HW, HH = 32, 21          # the game's real half-tile, from web/src/render/iso.ts
PX_PER_TILE_Z = 38       # how tall one "tile unit" of height draws

def sx(x, y): return (x - y) * HW
def sy(x, y): return (x + y) * HH

def mul(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c[:3]) + ((c[3],) if len(c) > 3 else ())

def mix(a, b, t):
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))


# --------------------------------------------------------------------------
# STYLE: the whole art direction, as data
# --------------------------------------------------------------------------
class Style:
    def __init__(self, key, name, pal, *, outline=None, outline_w=1, top=1.0,
                 right=0.80, left=0.60, radius=0, shadow=0.0, rim=None,
                 char=None, grain=0.0, edge_light=None, bg=None):
        self.key, self.name, self.pal = key, name, pal
        self.outline, self.outline_w = outline, outline_w
        self.top, self.right, self.left = top, right, left
        self.radius, self.shadow, self.rim = radius, shadow, rim
        self.char = char or {}
        self.grain, self.edge_light = grain, edge_light
        self.bg = bg or pal["bg"]

    def c(self, k):
        return self.pal[k]


