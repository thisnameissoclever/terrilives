"""Five ORIGINAL isometric art directions, drawn from scratch.

No Kenney. No pack. Every pixel here is generated by this file.

The bet: at a locked isometric camera and ~80 px per object, furniture is
shaded boxes. So one primitive renderer plus one object vocabulary plus a
STYLE (palette, outline, corner radius, shading model, character build)
gives a complete art direction, and five styles give five directions off
the same object list. That is [O2]/[O3] in TECH_STACK.md made real, and it
is also how the shipped game already draws its floor and its sim.
"""
