def sim(d, st, ox, oy, x, y, skin, hair, shirt, trouser, *, facing=1):
    """Drawn to the style's build: head ratio, shoulder width, stance."""
    ch = st.char
    H = ch.get("h", 86)
    head_r = H * ch.get("head", .21)
    px, py = ox + sx(x, y), oy + sy(x, y)
    ol, w = st.outline, st.outline_w
    sh = ch.get("shoulder", .34) * H
    hip = ch.get("hip", .26) * H
    leg = ch.get("leg", .38) * H
    torso = H - leg - head_r * 2
    slump = ch.get("slump", 0)

    if st.shadow:                                  # contact shadow
        d.ellipse([px - 14, py - 6, px + 14, py + 6],
                  fill=(0, 0, 0, int(150 * st.shadow)))

    ty = py - leg                                  # top of legs
    lw = hip * .42
    for s in (-1, 1):                              # legs
        cx = px + s * hip * .26
        d.rounded_rectangle([cx - lw / 2, ty, cx + lw / 2, py], radius=st.radius,
                            fill=trouser, outline=ol, width=w)
    # torso: a tapered body, wider at the shoulder
    top_y = ty - torso + slump
    body = [(px - sh / 2, top_y + torso * .18), (px - hip / 2, ty),
            (px + hip / 2, ty), (px + sh / 2, top_y + torso * .18)]
    if ch.get("bean"):
        d.rounded_rectangle([px - sh / 2, top_y, px + sh / 2, ty],
                            radius=int(sh * .48), fill=shirt, outline=ol, width=w)
    else:
        d.polygon(body + [(px + sh / 2, top_y), (px - sh / 2, top_y)],
                  fill=shirt, outline=ol, width=w)
    aw = sh * .22                                  # arms
    for s in (-1, 1):
        ax = px + s * (sh / 2 - aw * .3)
        d.rounded_rectangle([ax - aw / 2, top_y + torso * .1, ax + aw / 2, ty + leg * .12],
                            radius=st.radius or int(aw * .5), fill=mul(shirt, .92),
                            outline=ol, width=w)
    hy = top_y - head_r + slump                    # head
    if ch.get("square_head"):
        d.rounded_rectangle([px - head_r, hy - head_r, px + head_r, hy + head_r],
                            radius=int(head_r * .42), fill=skin, outline=ol, width=w)
    else:
        d.ellipse([px - head_r, hy - head_r, px + head_r, hy + head_r],
                  fill=skin, outline=ol, width=w)
    d.chord([px - head_r, hy - head_r, px + head_r, hy + head_r * .3],
            180, 360, fill=hair, outline=ol, width=w)          # hair cap
    ey = hy + head_r * .1                                       # eyes: one dot each
    r = max(1.2, head_r * .1)
    for s in (-1, 1):
        cx = px + s * head_r * .34 + facing * head_r * .06
        d.ellipse([cx - r, ey - r, cx + r, ey + r], fill=st.c("dark"))


